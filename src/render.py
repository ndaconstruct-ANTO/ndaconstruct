_GLYPH_W = 8
_GLYPH_H = 8

# Map a few common non-ASCII characters produced by LLMs to ASCII equivalents
# so they render instead of turning into blanks.
_TRANSLATE = str.maketrans(
    {
        "“": '"', "”": '"', "‘": "'", "’": "'",
        "–": "-", "—": "-", "…": "...", " ": " ",
        "•": "*", "®": "(R)", "™": "(TM)", "©": "(C)",
        "\t": "    ",
    }
)


def _wrap_lines(text: str, max_chars: int) -> list[str]:
    """Word-wrap ``text`` to at most ``max_chars`` columns, preserving blanks."""
    out: list[str] = []
    for raw in text.replace("\r\n", "\n").split("\n"):
        line = raw.translate(_TRANSLATE)
        if not line.strip():
            out.append("")
            continue
        words = line.split(" ")
        current = ""
        for word in words:
            # Hard-break a single word longer than the wrap width.
            while len(word) > max_chars:
                if current:
                    out.append(current)
                    current = ""
                out.append(word[:max_chars])
                word = word[max_chars:]
            candidate = word if not current else current + " " + word
            if len(candidate) <= max_chars:
                current = candidate
            else:
                out.append(current)
                current = word
        out.append(current)
    return out


def _write_png(path: Path, width: int, height: int, pixels: bytearray) -> None:
    """Write an 8-bit RGB PNG. ``pixels`` is height*width*3 bytes, row-major."""

    def chunk(tag: bytes, data: bytes) -> bytes:
        return (
            struct.pack(">I", len(data))
            + tag
            + data
            + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
        )

    stride = width * 3
    raw = bytearray()
    for y in range(height):
        raw.append(0)  # filter type 0 (None) for each scanline
        raw.extend(pixels[y * stride : (y + 1) * stride])

    ihdr = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
    png = (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", ihdr)
        + chunk(b"IDAT", zlib.compress(bytes(raw), 9))
        + chunk(b"IEND", b"")
    )
    path.write_bytes(png)


def render_text_to_png(
    text: str,
    path: Path,
    *,
    scale: int = 2,
    max_chars: int = 88,
    margin: int = 24,
    line_spacing: int = 4,
) -> Path:
    """Render ``text`` to a PNG at ``path`` and return the path."""
    lines = _wrap_lines(text, max_chars)
    if not lines:
        lines = [""]

    cell_w = _GLYPH_W * scale
    cell_h = _GLYPH_H * scale
    line_h = cell_h + line_spacing * scale

    width = margin * 2 + max_chars * cell_w
    height = margin * 2 + len(lines) * line_h

    # White canvas.
    pixels = bytearray(b"\xff" * (width * height * 3))
    stride = width * 3

    def set_block(px: int, py: int) -> None:
        for dy in range(scale):
            base = (py + dy) * stride + px * 3
            for dx in range(scale):
                off = base + dx * 3
                pixels[off] = 0
                pixels[off + 1] = 0
                pixels[off + 2] = 0

    for row, line in enumerate(lines):
        oy = margin + row * line_h
        for col, ch in enumerate(line):
            glyph = _FONT8X8.get(ch)
            if glyph is None:
                continue
            ox = margin + col * cell_w
            for gy in range(_GLYPH_H):
                bits = glyph[gy]
                if not bits:
                    continue
                for gx in range(_GLYPH_W):
                    if bits & (1 << gx):
                        set_block(ox + gx * scale, oy + gy * scale)

    _write_png(path, width, height, pixels)
    return path
